// moduleRegistry.js – реестр cleanup-функций модулей карты.
//
// core.js должен уничтожать/переинициализировать состояние всех модулей
// при повторном initCy() (защитный паттерн на случай переинициализации
// карты на одной странице). Раньше для этого core.js импортировал cleanup
// каждого модуля лично — список рос с каждым новым модулем (за последние
// несколько правок список вырос с 3 до 5 записей), и легко забыть добавить
// новый модуль в core.js при его создании. Теперь модуль сам регистрирует
// свою cleanup-функцию при первом импорте, а core.js просто вызывает
// cleanupAll() — ничего не зная о том, сколько и каких модулей есть.
const cleanupFns = [];

/**
 * Зарегистрировать cleanup-функцию модуля. Вызывать один раз на верхнем
 * уровне модуля (сработает при первом импорте — ES-модули кэшируются,
 * повторного импорта/повторной регистрации не будет).
 */
export function registerCleanup(fn) {
    if (typeof fn === 'function') cleanupFns.push(fn);
}

/**
 * Вызвать все зарегистрированные cleanup-функции. Ошибка в одной из них
 * не должна останавливать очистку остальных — оборачиваем каждую в try/catch.
 */
export function cleanupAll() {
    cleanupFns.forEach(fn => {
        try {
            fn();
        } catch (err) {
            console.error('[ModuleRegistry] Ошибка в cleanup-функции:', err);
        }
    });
}
